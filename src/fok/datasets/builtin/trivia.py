"""Curated trivia-style dataset (audit C2 rewrite, expanded for statistical power).

The purpose is the simplest "knowledge state" contrast:
``knowable=1`` -> common facts the model verifiably knows;
``knowable=0`` -> facts about *invented* entities that no model can have.

C2 fix: the old dataset contrasted short, ordinary known questions against long
questions full of invented rare-token names (Zoltir, Zvarkovo, ...), so TF-IDF
and length separated the classes with AUC 1.0 (audit A2). This version is a set
of **hand-matched pairs**: each known question has an unknowable twin that uses
the *same sentence frame and comparable length*, differing only in a
normal-looking invented entity. The known and unknown lists are therefore
stylistically indistinguishable, which the ``simple_baselines`` check verifies.

Scale: the original C2 rewrite had only 20 pairs (40 examples). With a 60/20
split that left ``n_test=6`` per class, so the permutation control was
underpowered and the result was not significant (p=0.08) even though the hidden
signal looked 1.0. This expanded version adds many more matched pairs so the
test slice is large enough (n_test ~30/class) for the control to have power.
"""

